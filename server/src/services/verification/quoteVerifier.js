/**
 * Deterministic Quote Verifier
 * 1. Checks that every cited span ID exists in the case.
 * 2. Checks that the quote appears in that span's text (whitespace-normalised exact match).
 * If either fails, marks claim status as Rejected with reason "citation failed".
 */

export function normaliseWhitespace(str) {
  if (!str || typeof str !== 'string') return '';
  return str.replace(/\s+/g, ' ').trim();
}

export function verifyClaimCitations(claim, spansMap) {
  if (!claim.spanRefs || claim.spanRefs.length === 0) {
    // Gap or synthetic claim without spans (e.g. Missing claims generated by gap detector)
    if (claim.status === 'Missing') {
      return {
        isValid: true,
        validatedSpanRefs: [],
      };
    }
    return {
      isValid: false,
      reason: 'citation failed: No span citations provided',
      validatedSpanRefs: [],
    };
  }

  const validatedSpanRefs = [];
  let allQuotesMatched = true;
  let failureReason = '';

  for (const ref of claim.spanRefs) {
    const span = spansMap.get(ref.spanId);

    if (!span) {
      allQuotesMatched = false;
      failureReason = `citation failed: Cited span ID ${ref.spanId} does not exist in this case`;
      validatedSpanRefs.push({
        ...ref,
        validated: false,
      });
      break;
    }

    const normQuote = normaliseWhitespace(ref.quote);
    const normSpanText = normaliseWhitespace(span.text);

    if (!normQuote) {
      allQuotesMatched = false;
      failureReason = 'citation failed: Cited quote is empty';
      validatedSpanRefs.push({
        ...ref,
        validated: false,
      });
      break;
    }

    // Check whitespace-normalised substring match
    if (normSpanText.includes(normQuote)) {
      validatedSpanRefs.push({
        ...ref,
        validated: true,
        sourceName: span.sourceName || '',
      });
    } else {
      allQuotesMatched = false;
      failureReason = `citation failed: Quote "${ref.quote.substring(0, 40)}..." was not found in span ${ref.spanId}`;
      validatedSpanRefs.push({
        ...ref,
        validated: false,
      });
      break;
    }
  }

  return {
    isValid: allQuotesMatched,
    reason: failureReason,
    validatedSpanRefs,
  };
}
